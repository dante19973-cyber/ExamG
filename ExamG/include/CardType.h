#pragma once

// Тип карти — визначає, як карта поводиться на полі
// (юніт, герой, погодна карта, ріг, підміна чи спалення).
enum class CardType
{
    Unit,     // звичайний юніт
    Hero,     // герой (на нього не діють погода/спалення)
    Weather,  // погодна карта (знижує силу юнітів у ряду)
    Horn,     // ріг (подвоює силу юнітів у ряду)
    Decoy,    // підміна (повертає юніт із поля в руку)
    Scorch    // спалення (знищує найсильніших юнітів)
};

// Підтип спецкарти — потрібен, щоб відрізняти конкретний ефект
// усередині CardType::Weather/Horn/Decoy/Scorch.
enum class SpecialType
{
    None,
    Frost,        // мороз — б'є ближній бій
    Fog,          // туман — б'є дальній бій
    Rain,         // дощ — б'є облогу
    ClearWeather, // ясна погода — знімає всі погодні ефекти
    Horn,         // ріг
    Decoy,        // підміна
    Scorch        // спалення
};
